SKIP_BEFORE = re.compile(r'(et al\.?,?\s*\(?\d{4}[a-z]?,?\s*$|\d{4},\s*$|Eltner|Zheng|Doersch|paper|tutorial)', re.I)
pat = re.compile(r'(Sects?\.|Sections?|Chapters?)(\s+)(\d+(?:\.\d+){0,2}(?:\s*(?:,|and|–|-|to|&)\s*\d+(?:\.\d+){0,2})*)')
log = []
def fix(m):
    pre = m.group(0)
    ctx = m.string[max(0, m.start()-70):m.start()]
    if SKIP_BEFORE.search(ctx.split('.')[-1] if False else ctx[-45:]):
        log.append(('SKIP', pre.replace('\n',' '))); return pre
    body = m.group(3); key = re.sub(r'\s+', ' ', body)
    if m.group(1).startswith('Sect') and key == '1.4':
        return 'Chapter 1'
    if key in RANGE: new = RANGE[key]
    else:
        def tok(t):
            n = M.get(t.group(0))
            if n is None: log.append(('UNMAPPED', t.group(0), pre.replace('\n',' '))); return t.group(0)
            return n
        new = re.sub(r'\d+(?:\.\d+){0,2}', tok, key)
    return m.group(1) + m.group(2) + new
for f in sys.argv[1:]:
    t = open(f).read(); n = pat.sub(fix, t)
    out = os.path.join('restructure', os.path.basename(f).replace('.md', '.m.md')); open(out, 'w').write(n)
    print(f, '->', out, sum(1 for a, b in zip(t.split(), n.split()) if a != b), 'changed tokens')
for l in log: print(l)
